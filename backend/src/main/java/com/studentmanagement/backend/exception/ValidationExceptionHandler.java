package com.studentmanagement.backend.exception;

// Unit 3: Exception Handling
// Topics: Global Exception Handling and Validation Errors

import org.springframework.http.HttpStatus;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.MethodArgumentNotValidException;
import org.springframework.web.bind.annotation.ExceptionHandler;
import org.springframework.web.bind.annotation.RestControllerAdvice;

import java.util.HashMap;
import java.util.Map;

// Spring Boot: Handles validation errors globally.
@RestControllerAdvice
public class ValidationExceptionHandler {

    // Handles errors generated by @Valid.
    @ExceptionHandler(MethodArgumentNotValidException.class)
    public ResponseEntity<Map<String, String>> handleValidationException(
            MethodArgumentNotValidException exception) {

        // Unit 4: Generic Programming
        // Map stores field names and their error messages.
        Map<String, String> errors = new HashMap<>();

        // Collects validation errors from the request.
        exception.getBindingResult().getFieldErrors().forEach(error ->
                errors.put(error.getField(), error.getDefaultMessage())
        );

        // Returns HTTP 400 Bad Request.
        return new ResponseEntity<>(errors, HttpStatus.BAD_REQUEST);
    }
}